#!/usr/bin/env node
/**
 * Generates src/models.gen.js from oracle/backend model files:
 *  - per-zone win trees split into 19 time bins (JSON strings, parsed lazily),
 *  - the cross-continent xtrunk split the same way,
 *  - region -> facility maps per zone.
 * Splitting keeps each Worker run to parsing ~20 KB instead of ~1.4 MB, which
 * matters under the free plan's 10 ms CPU limit. Run before deploy and tests.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const MODELS = join(here, "..", "oracle", "backend");
const OUT = join(here, "src", "models.gen.js");

const ZONE_TREE = { 2: "winbins_growtree_z2.json", 4: "winbins_growtree.json", 6: "winbins_growtree_z6.json", 8: "winbins_growtree_z8.json", 344: "winbins_growtree_z344.json" };
const ZONE_SLUG = { 2: "indar", 4: "hossin", 6: "amerish", 8: "esamir", 344: "oshur" };
const LEVELS = ["trunk", "branch", "twig", "shoot", "leaf"];
const BINS = 19;

const load = (f) => JSON.parse(readFileSync(join(MODELS, f), "utf8"));

export function splitTree(tree) {
  const bins = Array.from({ length: BINS }, () => Object.fromEntries(LEVELS.map((l) => [l, {}])));
  for (const l of LEVELS) {
    for (const [k, v] of Object.entries(tree[l] || {})) {
      const b = parseInt(k.split(",")[0], 10);
      if (b >= 0 && b < BINS) bins[b][l][k] = v;
    }
  }
  return bins.map((b) => JSON.stringify(b));
}

export function splitCells(cells) {
  const bins = Array.from({ length: BINS }, () => ({}));
  for (const [k, v] of Object.entries(cells)) {
    const b = parseInt(k.split(",")[0], 10);
    if (b >= 0 && b < BINS) bins[b][k] = v;
  }
  return bins.map((b) => JSON.stringify(b));
}

export function buildModels() {
  const trees = {};
  for (const [z, f] of Object.entries(ZONE_TREE)) trees[z] = splitTree(load(f));
  const xtrunk = splitCells(load("winbins_xtrunk.json").cells);
  const regions = {};
  for (const [z, slug] of Object.entries(ZONE_SLUG)) regions[z] = load(`${slug}_region_to_facility.json`);
  // Commander lattice: links in file order + base names, per zone.
  const lattice = {};
  for (const [z, slug] of Object.entries(ZONE_SLUG)) {
    lattice[z] = {
      links: load(`${slug}_links.json`).map((l) => [String(l.facility_id_a), String(l.facility_id_b)]),
      names: Object.fromEntries(load(`${slug}_regions.json`).map((r) => [String(r.facility_id), r.facility_name])),
    };
  }
  // Capture model per continent (commander_live.load_capture_model reads the same
  // <slug>_capture_model.json files). Hossin's came from hossin_models.py; the others
  // from oracle-worker/history/capture-model.mjs (PS2Alerts history, #63).
  const capture = Object.fromEntries(Object.entries(ZONE_SLUG)
    .filter(([, slug]) => existsSync(join(MODELS, `${slug}_capture_model.json`)))
    .map(([z, slug]) => [z, load(`${slug}_capture_model.json`).per_facility || {}]));
  // Resistance (hold-factor) model for all five continents (#24), same files as
  // commander_live.RESISTANCE_FILE: Hossin keeps base_resistance.json, the others
  // base_resistance_<slug>.json.
  const RES_FILE = { 2: "base_resistance_indar.json", 4: "base_resistance.json", 6: "base_resistance_amerish.json", 8: "base_resistance_esamir.json", 344: "base_resistance_oshur.json" };
  const resistance = Object.fromEntries(Object.entries(RES_FILE).map(([zone, file]) => [zone,
    Object.fromEntries(Object.entries(load(file)).map(([k, v]) => [k, { median_hold_min: v.median_hold_min ?? null, class: v.class ?? null }]))]));
  return { trees, xtrunk, regions, lattice, capture, resistance };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const m = buildModels();
  const src = "// GENERATED by build-trees.mjs from oracle/backend — do not edit.\n" +
    `export const TREE_BINS = ${JSON.stringify(m.trees)};\n` +
    `export const XTRUNK_BINS = ${JSON.stringify(m.xtrunk)};\n` +
    `export const REGION_TO_FACILITY = ${JSON.stringify(m.regions)};\n` +
    `export const LATTICE = ${JSON.stringify(m.lattice)};\n` +
    `export const CAPTURE = ${JSON.stringify(m.capture)};\n` +
    `export const RESISTANCE = ${JSON.stringify(m.resistance)};\n`;
  writeFileSync(OUT, src);
  console.log(`wrote ${OUT} (${(src.length / 1024).toFixed(0)} KB)`);
}
