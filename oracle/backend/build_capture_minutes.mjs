// Builds oracle/backend/capture_minutes.json (per-type table from claude/CAPTURE_MINUTES.md, one entry per
// facility from the *_regions.json files) and oracle-worker/src/capture-minutes.gen.js (facility_id -> minutes;
// Infinity = cannot be captured). Re-run after any *_regions.json rebuild.
import { readFileSync, writeFileSync } from "node:fs";

// All-points capture timer by Census facility_type_id (CAPTURE_MINUTES.md). null = no sourced number.
const BY_TYPE = {
  6: { name: "Small Outpost", minutes: 4, confidence: "medium" },
  5: { name: "Large Outpost", minutes: 7, confidence: "medium" },
  4: { name: "Tech Plant", minutes: 7, confidence: "medium" },
  2: { name: "Amp Station", minutes: 7, confidence: "medium" },
  3: { name: "Bio Lab", minutes: 3, confidence: "low" },
  9: { name: "Construction Outpost (vehicle outpost)", minutes: 1, confidence: "user-stated" },
  7: { name: "Warpgate", capturable: false },
  0: { name: "untyped", capturable: false },
};
const REGIONS = ["indar", "hossin", "amerish", "esamir", "oshur"];

const per_facility = {};
for (const slug of REGIONS) {
  const regions = JSON.parse(readFileSync(new URL(`./${slug}_regions.json`, import.meta.url), "utf8"));
  for (const r of regions) {
    const t = BY_TYPE[r.facility_type_id] || {};
    if (per_facility[r.facility_id]) throw new Error(`duplicate facility_id ${r.facility_id}`);
    per_facility[r.facility_id] = {
      name: r.facility_name, continent: slug, facility_type_id: +r.facility_type_id,
      capture_minutes_all_points: t.minutes ?? null, confidence: t.confidence ?? null, capturable: t.capturable ?? true,
    };
  }
}
writeFileSync(new URL("./capture_minutes.json", import.meta.url),
  JSON.stringify({ meta: { source: "claude/CAPTURE_MINUTES.md", built_by: "build_capture_minutes.mjs" }, by_type: BY_TYPE, per_facility }, null, 1) + "\n");

const lines = Object.entries(per_facility)
  .filter(([, v]) => v.capture_minutes_all_points != null || !v.capturable)
  .map(([fid, v]) => `  ${fid}: ${v.capturable ? v.capture_minutes_all_points : "Infinity"}, // ${v.name}`);
writeFileSync(new URL("../../oracle-worker/src/capture-minutes.gen.js", import.meta.url),
  "// GENERATED by oracle/backend/build_capture_minutes.mjs from claude/CAPTURE_MINUTES.md. Do not edit.\n" +
  "// facility_id -> all-points capture minutes; Infinity = cannot be captured. Unlisted = unknown (facility.js default).\n" +
  "export const CAPTURE_MINUTES = {\n" + lines.join("\n") + "\n};\n");
console.log("facilities:", Object.keys(per_facility).length, "with minutes or uncapturable:", lines.length);
