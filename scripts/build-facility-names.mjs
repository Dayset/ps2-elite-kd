#!/usr/bin/env node
/**
 * Writes worker/src/facility-names.js from the oracle's region files
 * (oracle/backend/<slug>_regions.json): facility_id → [name, zone, type].
 * The cache Worker's 📍 locator and live fight totals answer with base names,
 * so the site needs no extra download. test/live-map.test.mjs keeps it in sync.
 *   node scripts/build-facility-names.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const ZONE_OF_SLUG = { indar: 2, hossin: 4, amerish: 6, esamir: 8, oshur: 344 };

export function buildFacilityNames(root = ROOT) {
  const out = {};
  for (const [slug, zone] of Object.entries(ZONE_OF_SLUG)) {
    const rows = JSON.parse(fs.readFileSync(path.join(root, "oracle/backend", `${slug}_regions.json`), "utf8"));
    for (const r of rows) {
      const id = String(r.facility_id || "");
      if (!/^\d+$/.test(id) || !r.facility_name) continue;
      out[id] = [String(r.facility_name), zone, +r.facility_type_id || 0];
    }
  }
  const keys = Object.keys(out).sort((a, b) => +a - +b);
  const body = keys.map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(out[k])},`).join("\n");
  return "// Generated by scripts/build-facility-names.mjs from oracle/backend/*_regions.json. Do not edit.\n" +
    "// facility_id → [name, zone, facility_type_id]\n" +
    `export const FACILITY = {\n${body}\n};\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const file = path.join(ROOT, "worker/src/facility-names.js");
  fs.writeFileSync(file, buildFacilityNames());
  console.log(`wrote ${path.relative(ROOT, file)}`);
}
