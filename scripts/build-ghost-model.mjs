#!/usr/bin/env node
/** Fit the 👻 ghost population model over data/players/*.json → data/ghost-model.mjs. */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { normalizePlayer, playerMetrics } from "../player-metrics.mjs";
import { fitGhostModel } from "../ghost.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "data", "players");
const samples = [];
for (const f of fs.readdirSync(dir).filter((f) => f.endsWith(".json"))) {
  try {
    const p = normalizePlayer(JSON.parse(fs.readFileSync(path.join(dir, f), "utf8")));
    if (!p.rows || !p.rows.length) continue;
    samples.push({ rows: p.rows, metrics: playerMetrics(p) });
  } catch {
    /* skip unreadable */
  }
}
const model = fitGhostModel(samples);
const round = (v) => (typeof v === "number" ? +v.toPrecision(6) : v);
const json = JSON.stringify(model, (k, v) => round(v));
const out = `/** Generated by scripts/build-ghost-model.mjs from ${samples.length} cached players (${model.n} with a usable shape). Do not edit. */\nexport default ${json};\n`;
fs.writeFileSync(path.join(root, "data", "ghost-model.mjs"), out);
console.log(`ghost model: ${model.n}/${samples.length} players, sigma ${model.sigma.toFixed(3)}`);
console.log("A:", model.A.b0.toFixed(3), model.A.b.map((x) => x.toFixed(3)).join(" "));
console.log("S:", model.S.b0.toFixed(3), model.S.b.map((x) => x.toFixed(3)).join(" "));
